package transportguard

import (
	"fmt"
	"go/ast"
	"go/token"
	"sort"
	"strconv"
	"strings"
)

// SourceCategory names where the value written into a text-carrying field
// came from. Every write falls into exactly one named category, resolved
// only from the enclosing function's own body, parameters and receiver —
// never from a callee's body. An expression this cannot account for is a
// hard failure, never an implicit category.
type SourceCategory string

const (
	// SourceRouteBody is a value read through at least one field selector
	// rooted in a parameter of the enclosing function: the function
	// received it as part of the request body the route bound, and
	// forwards it on unchanged.
	SourceRouteBody SourceCategory = "value_from_route_body_parameter"
	// SourceInstanceConfig is a value read through the enclosing method's
	// own receiver: a long-lived field of the instance, never anything the
	// call received as an argument.
	SourceInstanceConfig SourceCategory = "value_from_instance_configuration"
	// SourceGoLiteral is a non-empty string literal composed in Go source:
	// prose written by this tree, not received from anywhere.
	SourceGoLiteral SourceCategory = "value_is_go_prose_literal"
	// SourceEmptyPlaceholder is a string literal whose content is empty: a
	// placeholder, declared as its own category — never prose, never
	// residue.
	SourceEmptyPlaceholder SourceCategory = "value_is_empty_placeholder"
	// SourceCallerResolved is a bare parameter of the enclosing function
	// used whole, with no field selected off it: an already-resolved
	// scalar the caller handed in, whose own further origin this guard
	// does not follow past this function's boundary.
	SourceCallerResolved SourceCategory = "value_resolved_by_caller_as_parameter"
	// SourceLibraryComputedValue is a value read off the result of a
	// method call whose receiver is not a type declared in this
	// production tree: a media upload's returned URL, a detected MIME
	// type, a parsed JID's string form. Generated by an imported package
	// at run time, never composed here and never the request body itself.
	SourceLibraryComputedValue SourceCategory = "value_computed_by_library_call"
	// SourceComposedByConcatenation is a value the tree builds by joining
	// operands with the string concatenation operator. It is its own
	// named category because the composite is neither of its parts: a
	// JSON envelope glued around a request-body field is not the
	// request-body field, and naming it one would hide the envelope. The
	// operands are classified recursively and kept in Parts, so the
	// enumeration shows what the composite is made of.
	SourceComposedByConcatenation SourceCategory = "value_composed_by_concatenation"
	// SourceBranchDependent is a value the enclosing function binds in
	// more than one branch, where the branches do not agree on a single
	// category. Reporting whichever branch came first would hide the
	// others, so the disagreement itself is the named category and every
	// branch is kept in Parts.
	SourceBranchDependent SourceCategory = "value_bound_differently_per_branch"
)

// FieldOrigin is the classified origin of one carrier field write inside a
// composite literal, with the file position of the value expression itself
// so a failure or an assertion can point at it exactly.
type FieldOrigin struct {
	File      string
	Line      int
	FieldName string
	Category  SourceCategory
	Reason    string
	// Parts holds the pieces this value was decomposed into: the
	// operands of a concatenation, flattened in source order, or the
	// bindings a local name takes inside the enclosing function. It is
	// empty for a value that is not made of other classified values.
	Parts []FieldOrigin
}

// Position renders the origin as "file:line".
func (o FieldOrigin) Position() string {
	return fmt.Sprintf("%s:%d", o.File, o.Line)
}

const maxValueOriginDepth = 12

// originResult is the internal result of classifying one expression: the
// named category, the written reason, and — for a concatenation — the
// classified parts.
type originResult struct {
	Category SourceCategory
	Reason   string
	Parts    []FieldOrigin
}

// classifyFieldOrigin resolves where the value written into fieldName came
// from. An unrecognized shape is a *GuardError naming "file:line", never a
// silently skipped field.
func (d *discoverer) classifyFieldOrigin(scope *fileScope, fn *ast.FuncDecl, fieldName string, expr ast.Expr) (FieldOrigin, error) {
	result, err := d.classifyValueOrigin(scope, fn, fieldName, expr, 0, false)
	if err != nil {
		return FieldOrigin{}, err
	}
	position := positionOf(d.fset, expr)
	return FieldOrigin{
		File:      position.Filename,
		Line:      position.Line,
		FieldName: fieldName,
		Category:  result.Category,
		Reason:    result.Reason,
		Parts:     result.Parts,
	}, nil
}

// classifyValueOrigin resolves the origin of expr. throughSelector records
// whether the path so far has crossed at least one field selector, which
// is what tells a parameter used whole ("valor resolvido no chamador")
// apart from a field read off a parameter ("corpo recebido pela rota").
func (d *discoverer) classifyValueOrigin(
	scope *fileScope,
	fn *ast.FuncDecl,
	fieldName string,
	expr ast.Expr,
	depth int,
	throughSelector bool,
) (originResult, error) {
	if depth > maxValueOriginDepth {
		return originResult{}, d.unresolvedValueError(expr, "could not be resolved within the hop limit")
	}
	switch e := expr.(type) {
	case *ast.ParenExpr:
		return d.classifyValueOrigin(scope, fn, fieldName, e.X, depth+1, throughSelector)
	case *ast.StarExpr:
		return d.classifyValueOrigin(scope, fn, fieldName, e.X, depth+1, throughSelector)
	case *ast.UnaryExpr:
		if e.Op != token.AND {
			return originResult{}, d.unresolvedValueError(expr, "is a unary operator other than address-of")
		}
		return d.classifyValueOrigin(scope, fn, fieldName, e.X, depth+1, throughSelector)
	case *ast.BasicLit:
		return d.classifyLiteral(e)
	case *ast.BinaryExpr:
		return d.classifyConcatenation(scope, fn, fieldName, e, depth, throughSelector)
	case *ast.CallExpr:
		return d.classifyCall(scope, fn, fieldName, e, depth, throughSelector)
	case *ast.SelectorExpr:
		return d.classifyValueOrigin(scope, fn, fieldName, e.X, depth+1, true)
	case *ast.Ident:
		return d.classifyIdent(scope, fn, fieldName, e, depth, throughSelector)
	}
	return originResult{}, d.unresolvedValueError(expr, fmt.Sprintf("is an expression shape (%T) this guard does not classify", expr))
}

// classifyConcatenation names a value the tree glues together with "+".
// Every operand is classified recursively and kept, flattened, in Parts,
// so a composite shows what it is made of instead of being reported as
// whichever operand happened to be looked at first. Any other binary
// operator on a text-carrying path is residue, not a category.
func (d *discoverer) classifyConcatenation(
	scope *fileScope,
	fn *ast.FuncDecl,
	fieldName string,
	expr *ast.BinaryExpr,
	depth int,
	throughSelector bool,
) (originResult, error) {
	if expr.Op != token.ADD {
		return originResult{}, d.unresolvedValueError(expr,
			"is a binary operator ("+expr.Op.String()+") other than string concatenation")
	}
	var parts []FieldOrigin
	for _, operand := range []ast.Expr{expr.X, expr.Y} {
		result, err := d.classifyValueOrigin(scope, fn, fieldName, operand, depth+1, throughSelector)
		if err != nil {
			return originResult{}, err
		}
		if result.Category == SourceComposedByConcatenation {
			// A left-nested chain of "+" is one concatenation, not a tree
			// of them, so its operands are spliced in rather than hidden
			// behind another composite.
			parts = append(parts, result.Parts...)
			continue
		}
		position := positionOf(d.fset, operand)
		parts = append(parts, FieldOrigin{
			File:      position.Filename,
			Line:      position.Line,
			FieldName: fieldName,
			Category:  result.Category,
			Reason:    result.Reason,
		})
	}
	summary := make([]string, 0, len(parts))
	for _, part := range parts {
		summary = append(summary, string(part.Category)+"@"+part.Position())
	}
	return originResult{
		Category: SourceComposedByConcatenation,
		Reason: "value is composed by concatenating " + strconv.Itoa(len(parts)) +
			" operands, each classified on its own: " + strings.Join(summary, ", "),
		Parts: parts,
	}, nil
}

// classifyCall resolves the origin of a value a call produces.
func (d *discoverer) classifyCall(
	scope *fileScope,
	fn *ast.FuncDecl,
	fieldName string,
	call *ast.CallExpr,
	depth int,
	throughSelector bool,
) (originResult, error) {
	// An immediately invoked function literal is a block that computes a
	// value in place. Its single returned expression is that value, and
	// the names it reads still belong to the enclosing function, so the
	// origin is resolved there instead of being given up as residue.
	if funcLit, ok := call.Fun.(*ast.FuncLit); ok {
		returned, err := singleReturnedExpr(funcLit)
		if err != nil {
			return originResult{}, d.unresolvedValueError(call, err.Error())
		}
		return d.classifyValueOrigin(scope, fn, fieldName, returned, depth+1, throughSelector)
	}
	// A call with exactly one argument is treated as boxing or
	// transforming that argument — proto.String(data.Caption),
	// stringPointer(reaction), findURL(data.Text) all have this shape —
	// so the origin of the argument is the origin of the value. When the
	// argument itself is not a shape this guard classifies (a struct
	// literal built just to pass to a helper, e.g.
	// utils.GenerateVC(utils.VCardStruct{...})), the call is tried again
	// as a library-computed value before being given up as residue.
	if len(call.Args) == 1 {
		if result, err := d.classifyValueOrigin(scope, fn, fieldName, call.Args[0], depth+1, throughSelector); err == nil {
			return result, nil
		}
		if result, ok := d.classifyLibraryComputedCall(scope, fn, call); ok {
			return result, nil
		}
		return originResult{}, d.unresolvedValueError(call.Args[0],
			"is an argument this guard does not classify, of a call it also cannot attribute to an imported package")
	}
	// A call whose receiver is not a production type returns a value some
	// imported package computed — a media upload's URL, a detected MIME
	// type, a generated vCard string — never a request body field or a Go
	// literal composed in this tree.
	if result, ok := d.classifyLibraryComputedCall(scope, fn, call); ok {
		return result, nil
	}
	return originResult{}, d.unresolvedValueError(call,
		"is a call with other than exactly one argument, and its callee is not attributable to an imported package")
}

// singleReturnedExpr returns the one expression an immediately invoked
// function literal gives back. More than one return statement, or a
// return of more than one value, is refused instead of guessed at.
func singleReturnedExpr(funcLit *ast.FuncLit) (ast.Expr, error) {
	var returns []*ast.ReturnStmt
	ast.Inspect(funcLit.Body, func(n ast.Node) bool {
		if nested, ok := n.(*ast.FuncLit); ok && nested != funcLit {
			return false
		}
		if ret, ok := n.(*ast.ReturnStmt); ok {
			returns = append(returns, ret)
		}
		return true
	})
	if len(returns) != 1 || len(returns[0].Results) != 1 {
		return nil, fmt.Errorf("is an invoked function literal with %d return statements this guard cannot reduce to one value", len(returns))
	}
	return returns[0].Results[0], nil
}

// classifyLibraryComputedCall reports whether call is a method call whose
// receiver is not a type this production tree declares — read with the
// resolver already built to tell production types from every other kind —
// and if so classifies its result as SourceLibraryComputedValue.
func (d *discoverer) classifyLibraryComputedCall(scope *fileScope, fn *ast.FuncDecl, call *ast.CallExpr) (originResult, bool) {
	selector, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return originResult{}, false
	}
	receiver := d.resolve.originOfValueExpr(scope, fn, selector.X, 0)
	switch receiver.Kind {
	case OriginTransportLibrary, OriginOtherPackage, OriginProto, OriginUnknown:
	default:
		return originResult{}, false
	}
	return originResult{
		Category: SourceLibraryComputedValue,
		Reason: "value is read from the result of calling " + selector.Sel.Name +
			" on a receiver of type " + receiver.Name + ", which this production tree does not declare" +
			" — generated by an imported package rather than composed here",
	}, true
}

func (d *discoverer) classifyLiteral(lit *ast.BasicLit) (originResult, error) {
	if lit.Kind != token.STRING {
		return originResult{}, d.unresolvedValueError(lit, "is a non-string literal")
	}
	content, err := strconv.Unquote(lit.Value)
	if err != nil {
		return originResult{}, d.unresolvedValueError(lit, "is a string literal that could not be unquoted")
	}
	if content == "" {
		return originResult{
			Category: SourceEmptyPlaceholder,
			Reason:   "value is the empty string literal, a declared placeholder rather than composed prose",
		}, nil
	}
	return originResult{
		Category: SourceGoLiteral,
		Reason:   literalReasonPrefix + strconv.Quote(content),
	}, nil
}

// classifyIdent classifies a bare identifier against the enclosing
// method's own receiver and the enclosing function's own parameters,
// before falling back to a local binding inside its body.
func (d *discoverer) classifyIdent(
	scope *fileScope,
	fn *ast.FuncDecl,
	fieldName string,
	ident *ast.Ident,
	depth int,
	throughSelector bool,
) (originResult, error) {
	if fn.Recv != nil && len(fn.Recv.List) > 0 {
		for _, name := range fn.Recv.List[0].Names {
			if name.Name == ident.Name {
				return originResult{
					Category: SourceInstanceConfig,
					Reason: "value is read through the method receiver " + ident.Name +
						", a field of the type this method is declared on, not anything the call received as an argument",
				}, nil
			}
		}
	}
	if fn.Type.Params != nil {
		for _, field := range fn.Type.Params.List {
			for _, name := range field.Names {
				if name.Name != ident.Name {
					continue
				}
				if throughSelector {
					return originResult{
						Category: SourceRouteBody,
						Reason: "value is read off a field selected from parameter " + ident.Name +
							", which the enclosing function received as its own argument",
					}, nil
				}
				return originResult{
					Category: SourceCallerResolved,
					Reason: "value is parameter " + ident.Name +
						" of the enclosing function itself, an already-resolved scalar handed in by the caller",
				}, nil
			}
		}
	}
	return d.classifyLocalIdent(scope, fn, fieldName, ident, depth, throughSelector)
}

// classifyLocalIdent classifies every statement in fn's own body — an
// assignment or a range clause — that binds ident, not only the first
// one. A switch that binds the same local in five branches puts five
// different values on the wire, and reporting whichever branch came
// first would let the other four through unread. It never looks outside
// fn: a name this function does not itself bind, receive as a parameter
// or hold as its receiver is unresolved.
func (d *discoverer) classifyLocalIdent(
	scope *fileScope,
	fn *ast.FuncDecl,
	fieldName string,
	ident *ast.Ident,
	depth int,
	throughSelector bool,
) (originResult, error) {
	bindings := localBindingsOf(fn, ident)
	if len(bindings) == 0 {
		return originResult{}, d.unresolvedValueError(ident,
			"is not bound by this function's receiver, parameters, assignments or range clauses")
	}

	var branches []FieldOrigin
	for _, binding := range bindings {
		// A range clause hands over one element of the ranged
		// expression, so reading it always crosses a selector: that is
		// what lets "for _, r := range data.Rows { ... r.Title ... }"
		// resolve to the same route-body origin as "data.Rows" itself.
		selector := throughSelector || binding.throughSelector
		result, err := d.classifyValueOrigin(scope, fn, fieldName, binding.value, depth+1, selector)
		if err != nil {
			return originResult{}, err
		}
		position := positionOf(d.fset, binding.value)
		branches = append(branches, FieldOrigin{
			File:      position.Filename,
			Line:      position.Line,
			FieldName: fieldName,
			Category:  result.Category,
			Reason:    result.Reason,
			Parts:     result.Parts,
		})
	}

	// The branch is kept in Parts even when there is only one of them,
	// so the position reported for the value is the place the value was
	// written rather than the place it was read.
	if len(branches) == 1 {
		return originResult{
			Category: branches[0].Category,
			Reason:   branches[0].Reason,
			Parts:    branches,
		}, nil
	}

	agreed := branches[0].Category
	for _, branch := range branches[1:] {
		if branch.Category != agreed {
			agreed = SourceBranchDependent
			break
		}
	}
	summary := make([]string, 0, len(branches))
	for _, branch := range branches {
		summary = append(summary, string(branch.Category)+"@"+branch.Position())
	}
	return originResult{
		Category: agreed,
		Reason: "value is the local name " + ident.Name + ", bound in " + strconv.Itoa(len(branches)) +
			" places inside this function, each classified on its own: " + strings.Join(summary, ", "),
		Parts: branches,
	}, nil
}

// localBinding is one place inside a function that binds a name, with the
// expression the name takes its value from.
type localBinding struct {
	value ast.Expr
	// throughSelector marks a binding that reads an element out of a
	// larger received value, such as a range clause.
	throughSelector bool
}

// localBindingsOf collects every assignment and range clause inside fn
// that binds ident, in source order.
func localBindingsOf(fn *ast.FuncDecl, ident *ast.Ident) []localBinding {
	var bindings []localBinding
	ast.Inspect(fn.Body, func(n ast.Node) bool {
		switch stmt := n.(type) {
		case *ast.AssignStmt:
			for i, lhs := range stmt.Lhs {
				lhsIdent, ok := lhs.(*ast.Ident)
				if !ok || lhsIdent.Name != ident.Name {
					continue
				}
				var rhs ast.Expr
				switch {
				case len(stmt.Rhs) == len(stmt.Lhs):
					rhs = stmt.Rhs[i]
				case len(stmt.Rhs) == 1:
					rhs = stmt.Rhs[0]
				}
				if rhs != nil {
					bindings = append(bindings, localBinding{value: rhs})
				}
			}
		case *ast.RangeStmt:
			if valueIdent, ok := stmt.Value.(*ast.Ident); ok && valueIdent.Name == ident.Name {
				bindings = append(bindings, localBinding{value: stmt.X, throughSelector: true})
			}
		}
		return true
	})
	return bindings
}

func (d *discoverer) unresolvedValueError(node ast.Node, problem string) error {
	return &GuardError{
		Location: positionOf(d.fset, node).String(),
		Message:  "value written into a text-carrying field " + problem,
	}
}

// OffRelaySource is one carrier field write whose origin is not the relay:
// it has to be asserted by name, so a new member derails the assertion
// instead of passing unnoticed.
type OffRelaySource struct {
	File        string
	Line        int
	MessageType string
	FieldName   string
	Category    SourceCategory
	Reason      string
}

// Position renders the off-relay source as "file:line".
func (s OffRelaySource) Position() string {
	return fmt.Sprintf("%s:%d", s.File, s.Line)
}

// OffRelaySources lists every carrier field write whose origin is not the
// relay, sorted by file and line for a stable comparison.
//
// Exactly one category is exempt, and it is exempt because the Goal
// itself declares it a category of its own that carries no text:
// SourceEmptyPlaceholder, the empty string literal, is the absence of a
// value. Every other category — instance configuration, Go literal,
// caller-resolved parameter, library-computed value and value composed by
// concatenation — is a value that is not the received request body, so it
// belongs in the asserted set and has to be accounted for by name.
func (e *Enumeration) OffRelaySources() []OffRelaySource {
	var out []OffRelaySource
	for _, site := range e.Sites {
		if site.Category == CategoryEmbeddedInLocalValue {
			// The value never reaches the wire, so it is not text the
			// transport delivers to a number.
			continue
		}
		for _, origin := range site.FieldOrigins {
			if origin.Category == SourceRouteBody || origin.Category == SourceEmptyPlaceholder {
				continue
			}
			out = append(out, OffRelaySource{
				File:        origin.File,
				Line:        origin.Line,
				MessageType: site.MessageType,
				FieldName:   origin.FieldName,
				Category:    origin.Category,
				Reason:      origin.Reason,
			})
		}
	}
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].File != out[j].File {
			return out[i].File < out[j].File
		}
		if out[i].Line != out[j].Line {
			return out[i].Line < out[j].Line
		}
		return out[i].FieldName < out[j].FieldName
	})
	return out
}

// GoProseLiteral is one non-empty string literal written in Go source
// that can reach a text-carrying field on the wire — as the whole value,
// as an operand of a concatenation, or as one branch's binding of the
// local the field reads. It is the finding the Goal's §2 exists to
// catch, and the set is asserted element by element so a new one fails
// the suite with its file, line and the fields it reaches.
type GoProseLiteral struct {
	File string
	Line int
	// Content is the literal's own text, exactly as the source spells it
	// once unquoted.
	Content string
	// Fields are the carrier fields this literal can reach, sorted and
	// without repetition.
	Fields []string
}

// Position renders the literal as "file:line".
func (l GoProseLiteral) Position() string {
	return fmt.Sprintf("%s:%d", l.File, l.Line)
}

// GoProseLiteralsReachingTransport lists every non-empty Go string
// literal that can reach a WhatsApp number through a text-carrying
// field. A literal written inside a value the transport never carries is
// not listed, because it never reaches a number.
//
// The reachability is deliberately over-approximate: when a field reads
// a local the function binds in several branches, every one of those
// bindings counts, because which branch runs is a run-time fact and this
// guard reads code. Over-approximation is the direction that keeps the
// rule fail-closed — a literal that could reach the wire is reported
// even when some path would not take it — and the cost is that a literal
// is attributed to more fields than one execution would use.
func (e *Enumeration) GoProseLiteralsReachingTransport() []GoProseLiteral {
	type key struct {
		file string
		line int
	}
	found := map[key]*GoProseLiteral{}
	fields := map[key]map[string]bool{}
	for _, site := range e.Sites {
		if site.Category == CategoryEmbeddedInLocalValue {
			continue
		}
		for _, origin := range site.FieldOrigins {
			for _, literal := range collectGoLiterals(origin) {
				id := key{file: literal.File, line: literal.Line}
				if found[id] == nil {
					found[id] = &GoProseLiteral{
						File:    literal.File,
						Line:    literal.Line,
						Content: literalContentOf(literal.Reason),
					}
					fields[id] = map[string]bool{}
				}
				fields[id][origin.FieldName] = true
			}
		}
	}
	out := make([]GoProseLiteral, 0, len(found))
	for id, literal := range found {
		names := make([]string, 0, len(fields[id]))
		for name := range fields[id] {
			names = append(names, name)
		}
		sort.Strings(names)
		literal.Fields = names
		out = append(out, *literal)
	}
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].File != out[j].File {
			return out[i].File < out[j].File
		}
		if out[i].Line != out[j].Line {
			return out[i].Line < out[j].Line
		}
		return out[i].Content < out[j].Content
	})
	return out
}

// literalReasonPrefix is the fixed head classifyLiteral writes before the
// quoted content of a non-empty Go literal.
const literalReasonPrefix = "value is a non-empty string literal written in Go source: "

// literalContentOf recovers the literal's own text from the written
// reason, so the asserted set names the string rather than the sentence.
func literalContentOf(reason string) string {
	quoted := strings.TrimPrefix(reason, literalReasonPrefix)
	content, err := strconv.Unquote(quoted)
	if err != nil {
		return quoted
	}
	return content
}

// collectGoLiterals walks an origin and the parts it was decomposed into
// — concatenation operands and per-branch bindings alike — and returns
// every non-empty Go literal found in it.
func collectGoLiterals(origin FieldOrigin) []FieldOrigin {
	if len(origin.Parts) > 0 {
		var out []FieldOrigin
		for _, part := range origin.Parts {
			out = append(out, collectGoLiterals(part)...)
		}
		return out
	}
	if origin.Category == SourceGoLiteral {
		return []FieldOrigin{origin}
	}
	return nil
}
